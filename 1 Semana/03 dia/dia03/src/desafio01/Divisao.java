package desafio01;

public class Divisao {
    public static void main(String[] args) {
        //Calcule a media de quatro notas.
        double nota1 = 7.5;
        double nota2 = 8.5;
        double nota3 = 4.5;
        double nota4 = 6.5;
        double media = (nota1 + nota2 + nota3 + nota4) / 4;
        System.out.println(media);


        //Converta a distancia de metros para kilometos
        double metros = 65000;
        double kilometros = 1000;
        double totalKm = metros / kilometros;
        System.out.println(totalKm);

    }

}
